// Local Tier 3 setup (docs/local-run.md): writes .dev.vars (git-ignored) with a freshly generated
// GitHub App key and development-only overrides, and .mock-github.json with the matching OIDC key.
// These keys exist only on your machine and only work against scripts/mock-github.js.
import { generateKeyPairSync } from "node:crypto";
import { writeFileSync } from "node:fs";
import { exportJWK } from "jose";

const app = generateKeyPairSync("rsa", { modulusLength: 2048 });
const oidc = generateKeyPairSync("rsa", { modulusLength: 2048 });
const pkcs1 = app.privateKey.export({ type: "pkcs1", format: "pem" }).toString().trim().replace(/\n/g, "\\n");
const jwk = { ...(await exportJWK(oidc.publicKey)), kid: "local-1", alg: "RS256", use: "sig" };

const port = process.env.MOCK_PORT ?? "8790";
const vars = [
  "# Generated by scripts/dev-setup.js. Local only. Never commit.",
  "ENVIRONMENT=development",
  "FEED_BASE=http://localhost:8788",
  "PUBLIC_URL=http://localhost:8787",
  "GITHUB_APP_ID=123456",
  `GITHUB_APP_PRIVATE_KEY=${pkcs1}`,
  `GITHUB_API_BASE=http://127.0.0.1:${port}`,
  `GITHUB_OIDC_ISSUER=http://127.0.0.1:${port}`,
  `GITHUB_JWKS_URL=http://127.0.0.1:${port}/jwks`,
  "",
].join("\n");
writeFileSync(".dev.vars", vars, "utf8");
writeFileSync(".mock-github.json", JSON.stringify({ jwks: { keys: [jwk] }, oidcPrivatePem: oidc.privateKey.export({ type: "pkcs8", format: "pem" }).toString() }), "utf8");
console.log("wrote .dev.vars and .mock-github.json (PKCS#1 app key, exactly what GitHub downloads)");
