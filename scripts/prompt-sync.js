// Prompt sync tooling (spec 4.4, Appendix C 45).
//   node scripts/prompt-sync.js generate           write src/prompts/summarizer.generated.ts
//   node scripts/prompt-sync.js check              fail if the generated module is stale
//   node scripts/prompt-sync.js compare <path>     compare with the template's summarizer_system.txt
// The template reads the file in text mode (Python), so CRLF becomes LF there; compare does the same.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "prompts/summarizer_system.txt");
const target = resolve(root, "src/prompts/summarizer.generated.ts");

const render = (text) =>
  "// GENERATED by scripts/prompt-sync.js from prompts/summarizer_system.txt. Do not edit.\n" +
  `export const SUMMARIZER_SYSTEM_PROMPT: string = ${JSON.stringify(text)};\n`;
const version = (text) => "p-" + createHash("sha256").update(text, "utf8").digest("hex").slice(0, 10);

const [, , command, other] = process.argv;
const text = readFileSync(source, "utf8").replace(/\r\n/g, "\n");

if (command === "generate") {
  writeFileSync(target, render(text), "utf8");
  console.log(`wrote ${target} (${version(text)})`);
} else if (command === "check") {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing file counts as stale
  }
  if (current !== render(text)) {
    console.error("generated prompt module is stale: run npm run prompt:generate");
    process.exit(1);
  }
  console.log(`generated prompt module is current (${version(text)})`);
} else if (command === "compare" && other) {
  const theirs = readFileSync(resolve(other), "utf8").replace(/\r\n/g, "\n");
  if (theirs === text) {
    console.log(`identical (${version(text)})`);
  } else if (theirs.replace(/\n+$/, "") === text.replace(/\n+$/, "")) {
    console.error(`DIFFERENT only in trailing newlines: gateway ${version(text)}, template ${version(theirs)}`);
    console.error("Fix: make the gateway file end like the template file, then npm run prompt:generate and update the pinned version in test/prompt.test.ts.");
    process.exit(1);
  } else {
    console.error(`DIFFERENT: gateway ${version(text)}, template ${version(theirs)}`);
    process.exit(1);
  }
} else {
  console.error("usage: node scripts/prompt-sync.js generate | check | compare <template summarizer_system.txt>");
  process.exit(2);
}
